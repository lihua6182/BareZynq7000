#!/usr/bin/env python3
"""Pack a 7-series Zynq bitstream for the ZBLZ loader."""

import argparse
import lzma
import os
import struct
import sys
import zlib
from typing import NoReturn

SYNC_BE = b"\xAA\x99\x55\x66"
SYNC_LE = b"\x66\x55\x99\xAA"
SYNC_SCAN = 128
# 19 per line = 117 columns: what clang-format (ColumnLimit 120) leaves alone.
PER_LINE = 19

LZMA_FILTERS = [{"id": lzma.FILTER_LZMA1, "preset": 9 | lzma.PRESET_EXTREME,
                 "lc": 0, "lp": 0, "pb": 0, "dict_size": 8192}]

MAGIC_LZMA = 0x5A4C425A
HDR_FMT = "<IIII"


def fail(msg: str) -> NoReturn:
    print(f"convert_bitstream.py: error: {msg}", file=sys.stderr)
    sys.exit(1)


def write_pair(out_c: str, out_h: str, c_body: str, c_comment: str, h_comment: str,
               length: int) -> None:
    name_c = os.path.basename(out_c)
    name_h = os.path.basename(out_h)
    guard = name_h.upper().replace(".", "_")
    with open(out_h, "w", newline="\n", encoding="ascii") as f:
        f.write(f"""/**
 * @file {name_h}
 * @brief {h_comment}
 *
 * Auto-generated by tools/convert_bitstream.py - DO NOT EDIT.
 */
#ifndef {guard}
#define {guard}

#include <stdint.h>

extern const uint8_t pl_img[];

#define PL_IMG_LEN ({length}U)

#endif
""")
    with open(out_c, "w", newline="\n", encoding="ascii") as f:
        f.write(f"""/**
 * @file {name_c}
 * @brief {c_comment}
 *
 * Auto-generated by tools/convert_bitstream.py - DO NOT EDIT.
 */
#include "{name_h}"

const uint8_t pl_img[PL_IMG_LEN] __attribute__((aligned(64))) = {{
{c_body}}};
""")


def to_pcap_form(raw: bytes, name: str) -> bytes:
    if len(raw) == 0 or len(raw) % 4 != 0:
        fail(f"{name}: size {len(raw)} is not a non-empty multiple of 4 (DevC DMA transfers whole 32-bit words)")
    head = raw[:SYNC_SCAN]
    be = head.find(SYNC_BE)
    le = head.find(SYNC_LE)
    if be >= 0 and le >= 0:
        fail(f"{name}: sync word found in both byte orders - cannot decide byte order")
    if be < 0 and le < 0:
        fail(f"{name}: no 0xAA995566 sync word in the first {SYNC_SCAN} bytes - not a 7-series bitstream?")
    if le >= 0:
        print(f"convert_bitstream.py: {name} is already in PCAP (little-endian) word order")
        return raw
    print(f"convert_bitstream.py: {name} is Vivado native (big-endian), swapping to PCAP word order")
    return b"".join(raw[i:i + 4][::-1] for i in range(0, len(raw), 4))


def lzma_encode(data: bytes) -> bytes:
    packed = lzma.compress(data, format=lzma.FORMAT_RAW, filters=LZMA_FILTERS)
    back = lzma.decompress(packed, format=lzma.FORMAT_RAW, filters=LZMA_FILTERS)
    if back != data:
        fail("lzma self-check: roundtrip mismatch")
    return packed


def main() -> None:
    ap = argparse.ArgumentParser(
        description="Pack a 7-series Zynq bitstream for the ZBLZ loader.")
    ap.add_argument("bitstream", help="input .bin (Vivado or PCAP order)")
    ap.add_argument("out_c")
    ap.add_argument("out_h")
    args = ap.parse_args()

    with open(args.bitstream, "rb") as f:
        raw = f.read()
    pcap = to_pcap_form(raw, args.bitstream)
    packed = lzma_encode(pcap)
    hdr = struct.pack(HDR_FMT, MAGIC_LZMA, len(pcap), len(packed),
                      zlib.crc32(pcap) & 0xFFFFFFFF)
    image = hdr + packed
    image += b"\x00" * (-len(image) % 4)

    lines = []
    for off in range(0, len(image), PER_LINE):
        chunk = image[off:off + PER_LINE]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    body = "\n".join(lines) + "\n"

    comment_c = (f"Packed PL bitstream: raw LZMA1 (lc=0 lp=0 pb=0, 8 KB dict, end marker)\n"
                 f" * over the PCAP-form (little-endian word order) image, with a 16-byte ZBLZ\n"
                 f" * header (magic, lengths, CRC-32).\n"
                 f" *   source  {args.bitstream} : {len(pcap)} bytes\n"
                 f" *   packed  {len(hdr)}-byte header + {len(packed)}-byte payload = "
                 f"{len(image)} bytes ({len(pcap) / len(image):.1f}:1)\n"
                 f" *   crc32 of the unpacked image: 0x{zlib.crc32(pcap) & 0xFFFFFFFF:08X}")
    comment_h = f"Packed PL bitstream ({len(image)} bytes, ZBLZ format)."
    write_pair(args.out_c, args.out_h, body, comment_c, comment_h, len(image))

    print(f"convert_bitstream.py: {len(pcap)} -> {len(image)} bytes "
          f"({len(pcap) / len(image):.1f}:1) -> {args.out_c}")


if __name__ == "__main__":
    main()
