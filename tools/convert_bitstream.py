#!/usr/bin/env python3
"""Pack a 7-series Zynq bitstream into the C array consumed by board_init()
(source/board/board.c).

  1. Convert to PCAP word order: Vivado 'write_bitstream -bin' emits
     big-endian words (sync bytes AA 99 55 66); the DevC/PCAP path wants
     little-endian (66 55 99 AA) - the "byte swapped .bin" of the
     kernel's zynq-fpga driver.
  2. RLE-encode in the SEGGER BSP_FPGA.c scheme (7-series images are
     mostly empty frames and padding, ~32:1):
       0x00        end of stream
       0x01..0x3F  literal run of <n> bytes           (n = c0)
       0x41..0x7F  repeat run of <n> copies of c1     (n = c0 - 0x3F)
       0x80..0xFF  zero run of <n> bytes              (n = c0 - 0x7F)
  3. Prepend a 16-byte LE header: magic "ZBSP" (also the load-path
     selector - bitgen images start with 0xFFFFFFFF padding), raw_len,
     packed_len, CRC-32 (EDB88320) over the raw image.
  4. Emit board_fpga_bitstream.c/board_fpga_bitstream.h defining the
     packed image as a 4 KB-aligned const array (fpga_img[]). The pair
     is data only - the code that consumes it is board_fpga.c.

Usage:
  convert_bitstream.py <bitstream.bin> <out.c> <out.h>   pack and emit the pair
  convert_bitstream.py --stub <out.c> <out.h>            no-bitstream stub
                                                         (target reports
                                                         PL_NO_IMAGE)

Exits non-zero (with a message) on any input problem.
"""

import os
import struct
import sys
import zlib

MAGIC = 0x5A425350  # "ZBSP"
HDR_FMT = "<IIII"  # magic, raw_len, packed_len, crc32
SYNC_BE = b"\xAA\x99\x55\x66"  # bitgen native word order
SYNC_LE = b"\x66\x55\x99\xAA"  # PCAP word order (what we must produce)
SYNC_SCAN = 128  # sync word sits inside this window in every bitgen layout
PER_LINE = 16  # array bytes per source line


def fail(msg: str) -> "NoReturn":  # type: ignore[valid-type]
    print(f"convert_bitstream.py: error: {msg}", file=sys.stderr)
    sys.exit(1)


def write_pair(out_c: str, out_h: str, c_body: str, c_comment: str, h_comment: str,
               length: int, c_decl: str) -> None:
    name_c = os.path.basename(out_c)
    name_h = os.path.basename(out_h)
    guard = name_h.upper().replace(".", "_")
    with open(out_h, "w", newline="\n", encoding="ascii") as f:
        f.write(f"""/**
 * @file {name_h}
 * @brief {h_comment}
 *
 * Auto-generated by tools/convert_bitstream.py - DO NOT EDIT.
 */
#ifndef {guard}
#define {guard}

#include <stdint.h>

extern const uint8_t fpga_img[];

#define FPGA_IMG_LEN {length}u

#endif /* {guard} */
""")
    with open(out_c, "w", newline="\n", encoding="ascii") as f:
        f.write(f"""/**
 * @file {name_c}
 * @brief {c_comment}
 *
 * Auto-generated by tools/convert_bitstream.py - DO NOT EDIT.
 */
#include "{name_h}"

const uint8_t fpga_img{c_decl} __attribute__((aligned(4096))) = {{
{c_body}}};
""")


def emit_stub(out_c: str, out_h: str) -> None:
    """Empty image: FPGA_IMG_LEN == 0 makes board_init() skip programming
    and report PL_NO_IMAGE. The definition carries one placeholder
    byte so C never sees a zero-size array."""
    comment = "Stub: this build embeds no PL bitstream (--stub conversion)."
    comment_c = (f"{comment}\n"
                 f" * The zero length makes board_init() skip programming.")
    write_pair(out_c, out_h, "    0x00,\n", comment_c, comment, 0, "[1]")
    print("convert_bitstream.py: stub pair written (no bitstream in this build)")


def to_pcap_form(raw: bytes, name: str) -> bytes:
    if len(raw) == 0 or len(raw) % 4 != 0:
        fail(f"{name}: size {len(raw)} is not a non-empty multiple of 4 (DevC DMA transfers whole 32-bit words)")
    head = raw[:SYNC_SCAN]
    be = head.find(SYNC_BE)
    le = head.find(SYNC_LE)
    if be >= 0 and le >= 0:
        fail(f"{name}: sync word found in both byte orders - cannot decide byte order")
    if be < 0 and le < 0:
        fail(f"{name}: no 0xAA995566 sync word in the first {SYNC_SCAN} bytes - not a 7-series bitstream?")
    if le >= 0:
        print(f"convert_bitstream.py: {name} is already in PCAP (little-endian) word order")
        return raw
    print(f"convert_bitstream.py: {name} is Vivado native (big-endian), swapping to PCAP word order")
    return b"".join(raw[i:i + 4][::-1] for i in range(0, len(raw), 4))


def rle_encode(data: bytes) -> bytes:
    out = bytearray()
    n = len(data)
    i = 0
    lit = bytearray()

    def flush_lit() -> None:
        nonlocal lit
        j = 0
        while j < len(lit):
            chunk = lit[j:j + 63]
            out.append(len(chunk))
            out.extend(chunk)
            j += len(chunk)
        lit = bytearray()

    while i < n:
        b = data[i]
        if b == 0:
            run = 1
            while run < 128 and i + run < n and data[i + run] == 0:
                run += 1
            flush_lit()
            out.append(0x7F + run)
            i += run
        else:
            run = 1
            while run < 64 and i + run < n and data[i + run] == b:
                run += 1
            if run >= 2:
                flush_lit()
                out.append(0x3F + run)
                out.append(b)
                i += run
            else:
                lit.append(b)
                i += 1
    flush_lit()
    out.append(0)
    return bytes(out)


def main() -> None:
    if len(sys.argv) == 4 and sys.argv[1] == "--stub":
        emit_stub(sys.argv[2], sys.argv[3])
        return
    if len(sys.argv) != 4:
        print(f"usage: {sys.argv[0]} [--stub] <out.c> <out.h>  "
              f"(pack: <bitstream.bin> <out.c> <out.h>)", file=sys.stderr)
        sys.exit(2)
    src, out_c, out_h = sys.argv[1], sys.argv[2], sys.argv[3]

    with open(src, "rb") as f:
        raw = f.read()
    pcap = to_pcap_form(raw, src)
    packed = rle_encode(pcap)
    hdr = struct.pack(HDR_FMT, MAGIC, len(pcap), len(packed), zlib.crc32(pcap) & 0xFFFFFFFF)
    image = hdr + packed
    # pl_load_image() requires a whole-word image length; the pad bytes sit
    # past packed_len, which the decoder never reads (pay_end comes from
    # the header).
    image += b"\x00" * (-len(image) % 4)

    lines = []
    for off in range(0, len(image), PER_LINE):
        chunk = image[off:off + PER_LINE]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    body = "\n".join(lines) + "\n"

    comment_c = (f"Packed PL bitstream: SEGGER-style RLE over the PCAP-form (little-endian\n"
                 f" * word order) image, with a 16-byte ZBSP header (magic, lengths, CRC-32).\n"
                 f" *   source  {src} : {len(pcap)} bytes\n"
                 f" *   packed  {len(hdr)}-byte header + {len(packed)}-byte payload = {len(image)} bytes ({len(pcap) / len(image):.1f}:1)\n"
                 f" *   crc32 of the unpacked image: 0x{zlib.crc32(pcap) & 0xFFFFFFFF:08X}")
    comment_h = f"Packed PL bitstream ({len(image)} bytes, ZBSP format)."
    write_pair(out_c, out_h, body, comment_c, comment_h, len(image), "[FPGA_IMG_LEN]")

    print(f"convert_bitstream.py: {len(pcap)} -> {len(image)} bytes ({len(pcap) / len(image):.1f}:1) -> {out_c}")


if __name__ == "__main__":
    main()
