/*
 * MIO/GPIO pin driver. One module, two halves, two number spaces that
 * share the low range (pin n == pad n, n < 54):
 *
 *   pad  0..53    MIO pads: function mux, pull-up, receiver, slew rate
 *                 (SLCR.MIO_PIN_xx, UG585 ch.6). EMIO has no pad.
 *   pin  0..117   GPIO controller (UG585 ch.14):
 *                   0..53   MIO  (bank 0: 0..31, bank 1: 32..53)
 *                  54..117  EMIO (bank 2: 54..85, bank 3: 86..117)
 *
 * Register primitives below are static inline and do no range checks;
 * configuration calls that can fail return 0 (ok) / -1 (out of range).
 *
 *   mio_enable_clock();
 *   mio_set_function(24, MIO24_GPIO);
 *   mio_direction_output(24, 0);
 *   mio_set_value(24, 1);
 *   v = mio_get_value(24);
 */

/* GPIO-controller pin space: 54 MIO + 64 EMIO. */
#define MIO_PIN_COUNT (118U)

/* mio_set_irq_type() argument, linux IRQ_TYPE_* naming. */
#define MIO_IRQ_TYPE_LEVEL_LOW    (0U) /* level sensitive, active low  */
#define MIO_IRQ_TYPE_LEVEL_HIGH   (1U) /* level sensitive, active high */
#define MIO_IRQ_TYPE_EDGE_FALLING (2U) /* falling edge                 */
#define MIO_IRQ_TYPE_EDGE_RISING  (3U) /* rising edge                  */
#define MIO_IRQ_TYPE_EDGE_BOTH    (4U) /* either edge                  */

/* ------------------------------------------------------------------ */
/* MIO pin mux and function selects                                   */
/* ------------------------------------------------------------------ */
/* Number of MIO pads (0..53); 54..117 are EMIO and need no pinmux. */
